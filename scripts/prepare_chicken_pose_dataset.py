"""Stage the Roboflow "Chicken pose all" v1 dataset for single-class training.

Source layout (Roboflow YOLOv8 export):
    <src>/{train,valid,test}/images/*.jpg
    <src>/{train,valid,test}/labels/*.txt    # 4 classes: drink, eat, moving, rest

Target layout (Ultralytics-friendly, single class):
    datasets/chicken-pose-all/
      images/{train,val,test}/*.jpg
      labels/{train,val,test}/*.txt          # all classes remapped to 0 = chicken
      data.yaml

Idempotent: re-running refreshes labels and skips already-present images.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SRC = REPO_ROOT / "Chicken pose all.v1i.yolov8"
DEFAULT_DST = REPO_ROOT / "datasets" / "chicken-pose-all"

# Roboflow → Ultralytics split-name mapping. Roboflow uses `valid`; we use `val`.
SPLIT_MAP = {"train": "train", "valid": "val", "test": "test"}


def remap_label_file(src_path: Path, dst_path: Path, target_class: int = 0) -> tuple[int, int]:
    """Copy a YOLO label file with every class id rewritten to `target_class`.

    Returns (lines_written, lines_skipped).
    """
    written = 0
    skipped = 0
    lines_out: list[str] = []
    for raw in src_path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 5:
            # Malformed — could be a pose label (class + bbox + keypoints) or junk.
            # Keep the bbox portion if it looks coherent, drop otherwise.
            skipped += 1
            continue
        # YOLO bbox format: <cls> <cx> <cy> <w> <h> [optional pose keypoints...]
        # Roboflow's "chicken-pose-all" v1 export uses plain bbox (5 cols), but
        # we slice defensively in case a pose variant is ever swapped in.
        bbox = parts[1:5]
        lines_out.append(f"{target_class} {' '.join(bbox)}")
        written += 1
    dst_path.parent.mkdir(parents=True, exist_ok=True)
    dst_path.write_text("\n".join(lines_out) + ("\n" if lines_out else ""), encoding="utf-8")
    return written, skipped


def stage_split(src_root: Path, dst_root: Path, src_split: str, dst_split: str) -> dict[str, int]:
    src_images = src_root / src_split / "images"
    src_labels = src_root / src_split / "labels"
    dst_images = dst_root / "images" / dst_split
    dst_labels = dst_root / "labels" / dst_split

    if not src_images.is_dir():
        raise FileNotFoundError(f"Missing source images dir: {src_images}")
    if not src_labels.is_dir():
        raise FileNotFoundError(f"Missing source labels dir: {src_labels}")

    dst_images.mkdir(parents=True, exist_ok=True)
    dst_labels.mkdir(parents=True, exist_ok=True)

    stats = {"images_copied": 0, "images_skipped": 0, "labels_written": 0, "boxes_remapped": 0, "boxes_skipped": 0}
    for img in src_images.iterdir():
        if not img.is_file():
            continue
        dst_img = dst_images / img.name
        if dst_img.exists() and dst_img.stat().st_size == img.stat().st_size:
            stats["images_skipped"] += 1
        else:
            shutil.copy2(img, dst_img)
            stats["images_copied"] += 1

        lbl = src_labels / (img.stem + ".txt")
        if lbl.is_file():
            written, skipped = remap_label_file(lbl, dst_labels / lbl.name)
            stats["labels_written"] += 1
            stats["boxes_remapped"] += written
            stats["boxes_skipped"] += skipped
        else:
            # Empty label file is valid (= no boxes). Mirror that.
            (dst_labels / (img.stem + ".txt")).write_text("", encoding="utf-8")
            stats["labels_written"] += 1

    return stats


def write_data_yaml(dst_root: Path) -> Path:
    yaml_path = dst_root / "data.yaml"
    # Absolute `path:` keeps Ultralytics from looking under its global
    # datasets_dir (which varies per machine). train/val/test are then
    # resolved relative to `path`.
    yaml_path.write_text(
        f"""# Auto-generated by scripts/prepare_chicken_pose_dataset.py.
# Source: Cornell University "chicken-pose-all" v1 (Roboflow, CC BY 4.0).
# All 4 behavior classes (drink/eat/moving/rest) collapsed to single class 0 = chicken.

path: {dst_root.resolve().as_posix()}
train: images/train
val: images/val
test: images/test

names:
  0: chicken
""",
        encoding="utf-8",
    )
    return yaml_path


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--src", type=Path, default=DEFAULT_SRC, help="Roboflow export folder.")
    p.add_argument("--dst", type=Path, default=DEFAULT_DST, help="Staged dataset target.")
    args = p.parse_args()

    src = args.src.resolve()
    dst = args.dst.resolve()
    if not src.is_dir():
        print(f"Source folder not found: {src}", file=sys.stderr)
        return 1

    print(f"▶ Staging: {src}")
    print(f"          → {dst}")
    totals: dict[str, int] = {}
    for src_split, dst_split in SPLIT_MAP.items():
        if not (src / src_split).is_dir():
            print(f"  · skip (missing): {src_split}")
            continue
        stats = stage_split(src, dst, src_split, dst_split)
        print(
            f"  · {src_split:<5} → {dst_split:<5}  "
            f"images: {stats['images_copied']} copied / {stats['images_skipped']} kept   "
            f"labels: {stats['labels_written']} files, "
            f"{stats['boxes_remapped']} boxes (+ {stats['boxes_skipped']} skipped)"
        )
        for k, v in stats.items():
            totals[k] = totals.get(k, 0) + v

    yaml_path = write_data_yaml(dst)
    print(f"\n✓ Wrote dataset YAML: {yaml_path}")
    print(f"  totals: {totals}")
    print(
        "\nNext:\n"
        f"  python scripts/train_bird_detector.py --data {yaml_path.relative_to(REPO_ROOT).as_posix()} "
        "--epochs 80 --version 1.1.0"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
